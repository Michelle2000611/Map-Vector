"""Implementation-independent boundaries of the application layer."""
from contextlib import contextmanager
from contextvars import ContextVar
from dataclasses import dataclass
from pathlib import Path
from typing import Callable,ContextManager,Iterable,Mapping,Protocol

class CursorPort(Protocol):
    def fetchone(self): ...
    def fetchall(self): ...
    def __iter__(self): ...

class SessionPort(Protocol):
    def execute(self,statement:str,parameters:Iterable=())->CursorPort: ...

class DatabasePort(Protocol):
    path:Path
    def read(self)->ContextManager[SessionPort]: ...
    def transaction(self)->ContextManager[SessionPort]: ...
    def initialize(self)->None: ...

class FeatureRepositoryPort(Protocol):
    def load(self,connection:SessionPort,feature_id:str)->dict: ...
    def restore(self,connection:SessionPort,feature:Mapping)->None: ...
    def update_index(self,connection:SessionPort,feature_id:str)->None: ...

class FileStoragePort(Protocol):
    def sha256(self,path:Path)->str: ...
    def atomic_bytes(self,path:Path,content:bytes)->None: ...
    def atomic_json(self,path:Path,content:object)->None: ...

class RasterPort(Protocol):
    max_bytes:int
    def probe(self,data:bytes): ...
    def sniff(self,data:bytes)->str: ...
    def decode(self,path:Path,kind:str,page_index:int,dpi:float): ...

class EditorPort(Protocol):
    face_layer:str
    line_layer:str
    error_type:type[Exception]
    def document(self,*args,**kwargs): ...
    def apply(self,*args,**kwargs): ...
    def render_frames(self,*args,**kwargs): ...
    def render(self,*args,**kwargs): ...
    def residual(self,*args,**kwargs): ...
    def png_bytes(self,*args,**kwargs): ...

class WorkerPort(Protocol):
    def run(self,*args,**kwargs): ...
    def is_alive(self,pid:int|None,identity:str)->bool: ...
    def export_arguments(self,python:str,project_dir:Path,project_id:str,export_id:str)->list[str]: ...
    def vector_arguments(self,python:str,raster:Path,output:Path)->list[str]: ...
    def ocr_arguments(self,python:str,raster:Path,output:Path,model:Path,engine:str)->list[str]: ...
    def package_versions(self,python:str,packages:list[str])->dict[str,str|None]: ...
    def source_root(self)->Path: ...
    def pinned_algorithm_paths(self)->list[Path]: ...
    def environment(self,project_root:Path)->dict[str,str]: ...

class ArchiveDatabasePort(Protocol):
    operational_error:type[Exception]
    def open(self,path:Path)->ContextManager[SessionPort]: ...
    def backup(self,source:SessionPort,target:SessionPort)->None: ...

class ProjectCatalogPort(Protocol):
    def create(self,name:str): ...
    def get(self,project_id:str): ...
    def list(self): ...

@dataclass(frozen=True)
class RuntimePorts:
    database:Callable[[Path],DatabasePort]
    features:FeatureRepositoryPort
    files:FileStoragePort
    raster:RasterPort
    editor:EditorPort
    workers:WorkerPort
    project_catalog:Callable[[Path],ProjectCatalogPort]
    write_gis:Callable
    archives:ArchiveDatabasePort

_ports:ContextVar[RuntimePorts|None]=ContextVar('mapvector_runtime_ports',default=None)
_default:RuntimePorts|None=None

def configure_ports(ports:RuntimePorts):
    global _default
    _default=ports

def get_ports()->RuntimePorts:
    value=_ports.get() or _default
    if value is None:raise RuntimeError('Application ports have not been composed')
    return value

@contextmanager
def use_ports(ports:RuntimePorts):
    token=_ports.set(ports)
    try:yield ports
    finally:_ports.reset(token)
